#!/usr/bin/env node

import { writeFile } from 'node:fs/promises';

const DEFAULT_AUTH_EMAIL_DOMAIN = 'brushing-master.example.com';
const OUTPUT_PATH = new URL('../prototype/supabase_config.local.js', import.meta.url);

const supabaseUrl = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL;
const publishableKey =
    process.env.SUPABASE_PUBLISHABLE_KEY ||
    process.env.SUPABASE_ANON_KEY ||
    process.env.VITE_SUPABASE_ANON_KEY;
const authEmailDomain = process.env.SUPABASE_AUTH_EMAIL_DOMAIN || DEFAULT_AUTH_EMAIL_DOMAIN;

function fail(message) {
    console.error(message);
    console.error('Usage: SUPABASE_URL=... SUPABASE_PUBLISHABLE_KEY=... npm run configure:supabase-local');
    process.exit(1);
}

function normalizeUrl(url) {
    return String(url || '').trim().replace(/\/$/, '');
}

function validateUrl(url) {
    if (!url || url === 'REPLACE_WITH_SUPABASE_PROJECT_URL') {
        fail('Missing SUPABASE_URL.');
    }

    let parsed;
    try {
        parsed = new URL(url);
    } catch {
        fail('SUPABASE_URL must be a valid URL.');
    }

    if (parsed.protocol !== 'https:') {
        fail('SUPABASE_URL must use https.');
    }

    if (!parsed.hostname.endsWith('.supabase.co') && parsed.hostname !== 'localhost') {
        fail('SUPABASE_URL should be a Supabase project URL.');
    }
}

function validatePublishableKey(key) {
    if (!key || key === 'REPLACE_WITH_SUPABASE_PUBLISHABLE_KEY') {
        fail('Missing SUPABASE_PUBLISHABLE_KEY or SUPABASE_ANON_KEY.');
    }

    if (key.includes('service_role')) {
        fail('Do not use a service role key in browser config.');
    }
}

function jsString(value) {
    return JSON.stringify(String(value));
}

validateUrl(normalizeUrl(supabaseUrl));
validatePublishableKey(publishableKey);

const content = `// Local-only Supabase override. Generated by scripts/write-supabase-local-config.mjs.
// This file is ignored by Git. Do not put service role or secret keys here.
window.BrushingMasterSupabaseConfig = {
    url: ${jsString(normalizeUrl(supabaseUrl))},
    publishableKey: ${jsString(publishableKey)},
    authEmailDomain: ${jsString(authEmailDomain)}
};
`;

await writeFile(OUTPUT_PATH, content, 'utf8');
console.log(`wrote ${OUTPUT_PATH.pathname}`);
